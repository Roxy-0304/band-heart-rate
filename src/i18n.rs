/// 格式化翻译文本（支持 {} 占位符）
pub fn tf(lang: &str, key: &str, args: &[&str]) -> String {
    let template = t(lang, key);
    let mut result = template.to_string();
    for arg in args {
        result = result.replacen("{}", arg, 1);
    }
    result
}
